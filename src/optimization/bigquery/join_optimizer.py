from __future__ import annotations

from typing import Any


# ============================================================
# CONSTANTS
# ============================================================

GIB = 1024 ** 3

LARGE_TABLE_BYTES = (
    10 * GIB
)

VERY_LARGE_TABLE_BYTES = (
    100 * GIB
)


# ============================================================
# OWNERSHIP BOUNDARY
# ============================================================
#
# These finding codes historically came from the general
# BigQueryOptimizer. Join-specific recommendation ownership now
# belongs to this module. The WebSocket integration filters these
# codes out of the general optimizer before merging evidence.
#
# Join *evidence* codes (for example BQ_CROSS_JOIN or
# BQ_TRANSFORMED_JOIN_KEY) remain owned by evidence_join.py.
# ============================================================

JOIN_OPTIMIZER_OWNED_GENERIC_FINDING_CODES = frozenset({
    "BQ_LARGE_JOIN_INPUT",
    "BQ_COMPLEX_JOIN_GRAPH",
})


# ============================================================
# HELPERS
# ============================================================

def _safe_int(
    value: Any,
) -> int | None:

    if value is None:

        return None

    try:

        return int(
            value
        )

    except (
        TypeError,
        ValueError,
    ):

        return None


def _format_bytes(
    value: int | None,
) -> str:

    if value is None:

        return "unknown"

    value = float(
        value
    )

    kib = 1024
    mib = 1024 ** 2
    gib = 1024 ** 3
    tib = 1024 ** 4

    if value >= tib:

        return (
            f"{value / tib:.3f} TiB"
        )

    if value >= gib:

        return (
            f"{value / gib:.2f} GiB"
        )

    if value >= mib:

        return (
            f"{value / mib:.2f} MiB"
        )

    if value >= kib:

        return (
            f"{value / kib:.2f} KiB"
        )

    return (
        f"{int(value)} bytes"
    )


def _opportunity(
    *,
    code: str,
    severity: str,
    title: str,
    message: str,
    recommendation: str,
    evidence: dict | None = None,
    rewrite_status: str = "RECOMMEND_ONLY",
    candidate_kind: str | None = None,
) -> dict:

    return {
        "code":
            code,

        "severity":
            severity,

        "category":
            "join_optimization",

        "title":
            title,

        "message":
            message,

        "recommendation":
            recommendation,

        "rewrite_status":
            rewrite_status,

        "candidate_kind":
            candidate_kind,

        "evidence":
            evidence
            or {},
    }


# ============================================================
# BIGQUERY JOIN OPTIMIZER
# ============================================================

class BigQueryJoinOptimizer:
    """
    Evidence-first BigQuery JOIN optimization intelligence.

    This component consumes deterministic JOIN evidence and emits
    structured optimization opportunities. It is the owner of
    join-specific recommendations/opportunities; the general
    BigQueryOptimizer should remain focused on non-join BigQuery
    rules.

    IMPORTANT:

    - It does NOT rewrite SQL.
    - It does NOT claim measured savings.
    - It does NOT claim runtime shuffle volume, join strategy,
      intermediate-result size, or post-filter cardinality.
    - Every future rewrite must be generated by a deterministic
      candidate generator and validated by BigQuery dry-run /
      quality-gate evidence.
    """

    def analyze(
        self,
        join_evidence: dict | None,
        structure=None,
    ) -> dict:

        evidence = (
            join_evidence
            or {}
        )

        edges = (
            evidence.get(
                "edges",
                [],
            )
            or []
        )

        opportunities = []

        # =====================================================
        # NO JOIN FAST PATH
        # =====================================================

        if not edges:

            return {
                "database_type":
                    "bigquery",

                "owned_generic_finding_codes":
                    sorted(
                        JOIN_OPTIMIZER_OWNED_GENERIC_FINDING_CODES
                    ),

                "opportunity_count":
                    0,

                "opportunities":
                    [],

                "recommendations":
                    [],

                "safe_rewrite_available":
                    False,

                "candidate_generation_allowed":
                    False,

                "summary": {
                    "join_count":
                        0,

                    "high_priority_count":
                        0,

                    "warning_count":
                        0,

                    "info_count":
                        0,
                },

                "limitations": [
                    (
                        "No join optimization opportunities were "
                        "evaluated because the query has no resolved "
                        "join edges."
                    )
                ],
            }

        # =====================================================
        # QUERY-LEVEL PROJECTION WIDTH
        # =====================================================

        if (
            structure is not None
            and
            getattr(
                structure,
                "has_select_star",
                False,
            )
        ):

            opportunities.append(
                _opportunity(
                    code=
                        "BQ_JOIN_WIDE_PROJECTION",

                    severity=
                        "warning",

                    title=
                        "Wide projection through a join",

                    message=
                        (
                            "The query contains a SELECT projection "
                            "wildcard while also containing JOINs. "
                            "Wide projections can carry unnecessary "
                            "columns through join processing."
                        ),

                    recommendation=
                        (
                            "Select only columns required by the "
                            "consumer. If the required output schema "
                            "is not known, request user intent before "
                            "generating a candidate."
                        ),

                    evidence={
                        "join_count":
                            len(
                                edges
                            ),

                        "select_star":
                            True,
                    },

                    rewrite_status=
                        "REQUIRES_USER_INTENT",

                    candidate_kind=
                        "COLUMN_PRUNING",
                )
            )

        # =====================================================
        # EDGE-LEVEL ANALYSIS
        # =====================================================

        for edge in edges:

            scope_index = (
                edge.get(
                    "scope_index"
                )
            )

            join_index = (
                edge.get(
                    "join_index"
                )
            )

            join_type = (
                edge.get(
                    "join_type"
                )
                or "UNKNOWN"
            )

            is_cross_join = bool(
                edge.get(
                    "is_cross_join"
                )
            )

            condition = (
                edge.get(
                    "condition"
                )
            )

            using_columns = (
                edge.get(
                    "using_columns",
                    [],
                )
                or []
            )

            transformed_pairs = (
                edge.get(
                    "transformed_equality_pairs",
                    [],
                )
                or []
            )

            equality_pairs = (
                edge.get(
                    "equality_pairs",
                    [],
                )
                or []
            )

            right_source = (
                edge.get(
                    "right_source"
                )
                or {}
            )

            right_table = (
                right_source.get(
                    "table"
                )
            )

            right_alias = (
                right_source.get(
                    "alias"
                )
            )

            left_aliases = (
                edge.get(
                    "referenced_left_aliases",
                    [],
                )
                or []
            )

            largest_left_size = (
                _safe_int(
                    edge.get(
                        "largest_left_size_bytes"
                    )
                )
            )

            right_size = (
                _safe_int(
                    edge.get(
                        "right_size_bytes"
                    )
                )
            )

            size_ratio = (
                edge.get(
                    "static_size_ratio"
                )
            )

            right_filtered = bool(
                edge.get(
                    "right_filtered"
                )
            )

            left_filtered_aliases = (
                edge.get(
                    "left_filtered_aliases",
                    [],
                )
                or []
            )

            risk_level = (
                edge.get(
                    "risk_level"
                )
                or "none"
            )

            common_evidence = {
                "scope_index":
                    scope_index,

                "join_index":
                    join_index,

                "join_type":
                    join_type,

                "left_aliases":
                    left_aliases,

                "right_alias":
                    right_alias,

                "right_table":
                    right_table,

                "condition":
                    condition,

                "equality_pairs":
                    equality_pairs,

                "largest_left_size_bytes":
                    largest_left_size,

                "right_size_bytes":
                    right_size,

                "static_size_ratio":
                    size_ratio,

                "risk_level":
                    risk_level,
            }

            # -------------------------------------------------
            # CROSS JOIN
            # -------------------------------------------------

            if is_cross_join:

                opportunities.append(
                    _opportunity(
                        code=
                            "BQ_OPT_CROSS_JOIN_REVIEW",

                        severity=
                            "warning",

                        title=
                            "Cartesian join review",

                        message=
                            (
                                "A CROSS JOIN is present. Cartesian "
                                "joins can expand row combinations "
                                "substantially when both inputs contain "
                                "multiple rows."
                            ),

                        recommendation=
                            (
                                "Verify that the Cartesian product is "
                                "intentional. If it is not intentional, "
                                "the correct join predicate must come "
                                "from user or application semantics."
                            ),

                        evidence=
                            common_evidence,

                        rewrite_status=
                            "REQUIRES_USER_INTENT",

                        candidate_kind=
                            "JOIN_CONDITION",
                    )
                )

            # -------------------------------------------------
            # JOIN WITHOUT CONDITION
            # -------------------------------------------------

            if (
                not is_cross_join
                and
                condition is None
                and
                not using_columns
            ):

                opportunities.append(
                    _opportunity(
                        code=
                            "BQ_OPT_MISSING_JOIN_CONDITION",

                        severity=
                            "warning",

                        title=
                            "Join condition required",

                        message=
                            (
                                "A JOIN has no deterministic ON or "
                                "USING condition."
                            ),

                        recommendation=
                            (
                                "Do not invent a predicate. Request "
                                "the intended relationship from the "
                                "user or application before creating "
                                "a candidate."
                            ),

                        evidence=
                            common_evidence,

                        rewrite_status=
                            "REQUIRES_USER_INTENT",

                        candidate_kind=
                            "JOIN_CONDITION",
                    )
                )

            # -------------------------------------------------
            # TRANSFORMED JOIN KEYS
            # -------------------------------------------------

            if transformed_pairs:

                transformed_evidence = dict(
                    common_evidence
                )

                transformed_evidence[
                    "transformed_equality_pairs"
                ] = transformed_pairs

                opportunities.append(
                    _opportunity(
                        code=
                            "BQ_OPT_TRANSFORMED_JOIN_KEY",

                        severity=
                            "info",

                        title=
                            "Transformed join key review",

                        message=
                            (
                                "At least one equality join key uses "
                                "an expression instead of a simple "
                                "column-to-column comparison."
                            ),

                        recommendation=
                            (
                                "Review whether the transformation is "
                                "required for correctness. A rewrite "
                                "is only safe when equivalent typed "
                                "keys or a precomputed normalized key "
                                "are proven to preserve semantics."
                            ),

                        evidence=
                            transformed_evidence,

                        rewrite_status=
                            "REQUIRES_SEMANTIC_PROOF",

                        candidate_kind=
                            "JOIN_KEY_NORMALIZATION",
                    )
                )

            # -------------------------------------------------
            # LARGE-LARGE JOIN
            # -------------------------------------------------

            if (
                largest_left_size is not None
                and
                right_size is not None
                and
                largest_left_size
                >=
                LARGE_TABLE_BYTES
                and
                right_size
                >=
                LARGE_TABLE_BYTES
            ):

                opportunities.append(
                    _opportunity(
                        code=
                            "BQ_OPT_LARGE_LARGE_JOIN",

                        severity=
                            "info",

                        title=
                            "Large-to-large join review",

                        message=
                            (
                                "Both sides of this join resolve to "
                                "large physical tables in static "
                                "metadata."
                            ),

                        recommendation=
                            (
                                "Prioritize this edge for measured "
                                "validation. Review projection width, "
                                "existing selective predicates, and "
                                "whether semantics permit aggregation "
                                "before the join. Do not assume static "
                                "table size equals runtime join input."
                            ),

                        evidence={
                            **common_evidence,

                            "largest_left_size_formatted":
                                _format_bytes(
                                    largest_left_size
                                ),

                            "right_size_formatted":
                                _format_bytes(
                                    right_size
                                ),
                        },

                        rewrite_status=
                            "RECOMMEND_ONLY",

                        candidate_kind=
                            "LARGE_JOIN_REVIEW",
                    )
                )

            # -------------------------------------------------
            # LARGE RIGHT INPUT
            # -------------------------------------------------

            elif (
                right_size is not None
                and
                right_size
                >=
                LARGE_TABLE_BYTES
            ):

                opportunities.append(
                    _opportunity(
                        code=
                            "BQ_OPT_LARGE_JOIN_INPUT",

                        severity=
                            "info",

                        title=
                            "Large join input review",

                        message=
                            (
                                "The right side resolves to a large "
                                "physical table in static metadata."
                            ),

                        recommendation=
                            (
                                "Review whether only required columns "
                                "are projected and whether an existing "
                                "business predicate can be applied "
                                "before the join. Validate any candidate "
                                "with BigQuery dry-run."
                            ),

                        evidence={
                            **common_evidence,

                            "right_size_formatted":
                                _format_bytes(
                                    right_size
                                ),
                        },

                        rewrite_status=
                            "RECOMMEND_ONLY",

                        candidate_kind=
                            "LARGE_JOIN_REVIEW",
                    )
                )

            # -------------------------------------------------
            # FILTER PLACEMENT
            # -------------------------------------------------

            if (
                (
                    right_filtered
                    or
                    left_filtered_aliases
                )
                and
                (
                    (
                        right_size is not None
                        and
                        right_size
                        >=
                        LARGE_TABLE_BYTES
                    )
                    or
                    (
                        largest_left_size is not None
                        and
                        largest_left_size
                        >=
                        LARGE_TABLE_BYTES
                    )
                )
            ):

                opportunities.append(
                    _opportunity(
                        code=
                            "BQ_OPT_FILTER_PLACEMENT_REVIEW",

                        severity=
                            "info",

                        title=
                            "Filter placement review",

                        message=
                            (
                                "A predicate references at least one "
                                "source participating in a join that "
                                "also has large static table metadata."
                            ),

                        recommendation=
                            (
                                "When semantics are unchanged, keep "
                                "source-specific filtering as early as "
                                "possible in the logical plan or source "
                                "subquery. Do not claim row reduction "
                                "without measured execution evidence."
                            ),

                        evidence={
                            **common_evidence,

                            "right_filtered":
                                right_filtered,

                            "left_filtered_aliases":
                                left_filtered_aliases,

                            "where_clause":
                                edge.get(
                                    "where_clause"
                                ),
                        },

                        rewrite_status=
                            "REQUIRES_SEMANTIC_PROOF",

                        candidate_kind=
                            "PREDICATE_PLACEMENT",
                    )
                )

            # -------------------------------------------------
            # PRE-AGGREGATION REVIEW
            # -------------------------------------------------
            #
            # We intentionally do NOT infer a many-side relationship.
            # This is surfaced only when a large join is present and
            # the query already contains aggregation evidence.
            # -------------------------------------------------

            aggregations = (
                getattr(
                    structure,
                    "aggregations",
                    [],
                )
                if structure is not None
                else []
            )

            if (
                aggregations
                and
                (
                    (
                        right_size is not None
                        and
                        right_size
                        >=
                        LARGE_TABLE_BYTES
                    )
                    or
                    (
                        largest_left_size is not None
                        and
                        largest_left_size
                        >=
                        LARGE_TABLE_BYTES
                    )
                )
            ):

                opportunities.append(
                    _opportunity(
                        code=
                            "BQ_OPT_PREAGGREGATION_REVIEW",

                        severity=
                            "info",

                        title=
                            "Pre-aggregation opportunity review",

                        message=
                            (
                                "The query contains aggregation and "
                                "this join involves a large physical "
                                "table according to static metadata."
                            ),

                        recommendation=
                            (
                                "Check whether an input can be "
                                "aggregated to the join-key grain before "
                                "the join without changing output "
                                "semantics. This must be proven before "
                                "a candidate is generated."
                            ),

                        evidence={
                            **common_evidence,

                            "aggregations":
                                aggregations,
                        },

                        rewrite_status=
                            "REQUIRES_SEMANTIC_PROOF",

                        candidate_kind=
                            "PRE_AGGREGATION",
                    )
                )

        # =====================================================
        # COMPLEX JOIN GRAPH
        # =====================================================

        if len(
            edges
        ) >= 3:

            opportunities.append(
                _opportunity(
                    code=
                        "BQ_OPT_COMPLEX_JOIN_GRAPH",

                    severity=
                        "info",

                    title=
                        "Complex join graph review",

                    message=
                        (
                            f"The query contains {len(edges)} resolved "
                            "join edges."
                        ),

                    recommendation=
                        (
                            "Prioritize high-risk or large-table edges "
                            "for measured analysis. Review projection "
                            "width, existing predicates, transformed "
                            "keys, and aggregation boundaries before "
                            "considering any rewrite."
                        ),

                    evidence={
                        "join_count":
                            len(
                                edges
                            ),
                    },

                    rewrite_status=
                        "RECOMMEND_ONLY",

                    candidate_kind=
                        "JOIN_GRAPH_REVIEW",
                )
            )

        opportunities = (
            self._deduplicate_opportunities(
                opportunities
            )
        )

        recommendations = [
            opportunity.get(
                "recommendation"
            )

            for opportunity
            in opportunities

            if opportunity.get(
                "recommendation"
            )
        ]

        warning_count = sum(
            1

            for opportunity
            in opportunities

            if (
                opportunity.get(
                    "severity"
                )
                ==
                "warning"
            )
        )

        info_count = sum(
            1

            for opportunity
            in opportunities

            if (
                opportunity.get(
                    "severity"
                )
                ==
                "info"
            )
        )

        high_priority_count = sum(
            1

            for opportunity
            in opportunities

            if (
                opportunity.get(
                    "code"
                )
                in {
                    "BQ_OPT_CROSS_JOIN_REVIEW",
                    "BQ_OPT_MISSING_JOIN_CONDITION",
                }
            )
        )

        candidate_generation_allowed = any(
            opportunity.get(
                "rewrite_status"
            )
            in {
                "READY_FOR_CANDIDATE",
            }

            for opportunity
            in opportunities
        )

        return {
            "database_type":
                "bigquery",

            "owned_generic_finding_codes":
                sorted(
                    JOIN_OPTIMIZER_OWNED_GENERIC_FINDING_CODES
                ),

            "opportunity_count":
                len(
                    opportunities
                ),

            "opportunities":
                opportunities,

            "recommendations":
                self._deduplicate_strings(
                    recommendations
                ),

            # No Phase-3C rule in this module currently authorizes
            # executable SQL generation.
            "safe_rewrite_available":
                False,

            "candidate_generation_allowed":
                candidate_generation_allowed,

            "summary": {
                "join_count":
                    len(
                        edges
                    ),

                "high_priority_count":
                    high_priority_count,

                "warning_count":
                    warning_count,

                "info_count":
                    info_count,
            },

            "limitations": [
                (
                    "Static table metadata is not runtime join input "
                    "size."
                ),
                (
                    "No shuffle bytes, slot usage, physical join "
                    "strategy, or intermediate-result cardinality are "
                    "claimed without execution-stage evidence."
                ),
                (
                    "This module emits recommendations only. SQL "
                    "rewrites require deterministic candidate "
                    "generation plus BigQuery dry-run quality-gate "
                    "validation."
                ),
            ],
        }

    # =========================================================
    # DEDUPLICATION
    # =========================================================

    def _deduplicate_opportunities(
        self,
        opportunities: list[dict],
    ) -> list[dict]:

        result = []

        seen = set()

        for opportunity in opportunities:

            evidence = (
                opportunity.get(
                    "evidence"
                )
                or {}
            )

            key = (
                opportunity.get(
                    "code"
                ),
                evidence.get(
                    "scope_index"
                ),
                evidence.get(
                    "join_index"
                ),
            )

            if key in seen:

                continue

            seen.add(
                key
            )

            result.append(
                opportunity
            )

        return result

    def _deduplicate_strings(
        self,
        values: list[str],
    ) -> list[str]:

        result = []

        seen = set()

        for value in values:

            if not value:

                continue

            normalized = (
                value.strip()
            )

            if normalized in seen:

                continue

            seen.add(
                normalized
            )

            result.append(
                normalized
            )

        return result